def ok(c, msg):
    print(('  ok   ' if c else '  FAIL ') + msg)
    if not c: fails.append(msg)

async def fill_form(pg, name, sex, age, h, w, act, goal, level, days, focus=None):
    """Completează formularul pe pași și se oprește la ultimul pas (Preferințe). Întoarce accentul propus automat."""
    await pg.fill('[name=name]', name)
    await pg.check(f'[name=sex][value={sex}]', force=True)
    await pg.fill('[name=age]', str(age)); await pg.fill('[name=h]', str(h)); await pg.fill('[name=w]', str(w))
    await pg.check(f'[name=act][value={act}]', force=True)
    await pg.click('[data-act=fnext]')
    await pg.check(f'[name=goal][value={goal}]', force=True)
    await pg.click('[data-act=fnext]')
    await pg.check(f'[name=level][value={level}]', force=True)
    await pg.check(f'[name=days][value="{days}"]', force=True)
    auto = await pg.eval_on_selector('[name=focus]:checked', 'e => e.value') if await pg.locator('[name=focus]:checked').count() else None
    if focus: await pg.check(f'[name=focus][value={focus}]', force=True)
    await pg.click('[data-act=fnext]')
    return auto

async def no_overflow(pg, label):
    over = await pg.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')
    ok(over <= 0, f'fără derulare orizontală: {label} ({over}px)')

